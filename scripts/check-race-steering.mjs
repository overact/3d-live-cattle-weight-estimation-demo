import assert from "node:assert/strict";
import * as THREE from "../vendor/three.module.js";
import { createRaceSteering } from "../js/lib/race-steering.js?v=20260907-ranch-drive-v6";
import { createThirdPersonRig } from "../js/lib/third-person-rig.js?v=20260907-ranch-drive-v6";
const integrate=(seconds,fps)=>{
  const steering=createRaceSteering();let yaw=0;
  for(let i=0;i<Math.round(seconds*fps);i++)yaw+=steering.step(1,1/fps,5.2);
  return yaw;
};
const tap=integrate(.1,60),held=integrate(.5,60);
assert.ok(tap>0.05&&tap<.18,"100ms tap gives a precise 3–10 degree correction");
assert.ok(held>Math.PI/2,"holding still turns a sharp corner in half a second");
assert.ok(Math.abs(integrate(1,30)-integrate(1,120))<1e-10,"same turn at 30 and 120 FPS");
const steering=createRaceSteering();steering.step(1,.5,5.2);
assert.ok(Math.abs(steering.step(1,.1,5.2)-.52)<1e-10,"sustained full turn rate is not reduced");
assert.equal(steering.step(0,.1,5.2),0,"release has no yaw overshoot");
steering.step(1,.5,5.2);
const reverse=steering.step(-1,.1,5.2);
assert.ok(reverse<0&&Math.abs(reverse-tap*-1)<1e-10,"opposite key immediately begins a gentle correction");
steering.reset();assert.ok(Math.abs(steering.step(1,.1,5.2)-tap)<1e-10);
const rig=createThirdPersonRig({camera:new THREE.PerspectiveCamera(55,1,.1,400),groundFn:()=>0});
rig.setRaceSteering(true);rig.teleport(0,0,0);rig.press("forward",true);rig.press("left",true);
for(let i=0;i<6;i++)rig.update(1/60);
assert.ok(Math.abs(rig.state.heading-tap)<1e-10);
rig.press("left",false);const heading=rig.state.heading;
rig.orbit(200,0);
for(let i=0;i<60;i++)rig.update(1/60);
assert.equal(rig.state.heading,heading,"camera follow/orbit cannot tug forward steering after release");
rig.press("left",true);rig.update(.3);rig.releaseAll();rig.press("left",true);const before=rig.state.heading;
rig.update(.1);assert.ok(Math.abs(rig.state.heading-before-tap)<1e-10,"pause/release resets ramp");
rig.setRaceSteering(false);rig.releaseAll();rig.teleport(0,0,0);rig.press("left",true);rig.update(.1);
assert.ok(Math.abs(rig.state.heading-.52)<1e-10,"free roam retains its camera-relative controls");
console.log(`Race steering verified: ${(tap*180/Math.PI).toFixed(1)}° tap, ${(held*180/Math.PI).toFixed(1)}° held corner, full-rate hold, release, reversal, camera independence, FPS parity and roam isolation.`);
